test("the inverse projection agrees with GDAL across the whole grid", () => {
  let worst = 0;
  for (const [x, y, lon, lat] of GDAL_LATTICE) {
    const [gotLon, gotLat] = inverseLcc(x, y);
    // Metres on the ground, so the tolerance means something physical
    // rather than being a bare count of decimal places.
    const metres = Math.hypot(
      (gotLat - lat) * 111320,
      (gotLon - lon) * 111320 * Math.cos((lat * Math.PI) / 180),
    );
    worst = Math.max(worst, metres);
  }
  // Measured at 2.9e-8 m over 2000 random points. A millimetre is far looser
  // than the agreement observed and still far tighter than the 30 m cell,
  // so a real divergence cannot hide under it.
  assert.ok(worst < 0.001, `worst disagreement with GDAL was ${worst} m`);
});
